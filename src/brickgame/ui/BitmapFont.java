    int textWidth(String text) {
        return textWidth(text, 1, 1);
    }

    int textWidth(String text, int scale, int spacing) {
        if (text == null || text.length() == 0) {
            return 0;
        }
        int width = 0;
        int i;
        for (i = 0; i < text.length(); i++) {
            int glyph = glyphIndex(text.charAt(i));
            width += WIDTHS[glyph] * scale;
            if (i + 1 < text.length()) {
                width += spacing;
            }
        }
        return width;
    }

    void draw(Graphics graphics, String text, int x, int y, int color) {
        draw(graphics, text, x, y, color, 1, 1);
    }

    void drawCentered(Graphics graphics, String text, int centerX, int y, int color) {
        draw(graphics, text, centerX - textWidth(text) / 2, y, color, 1, 1);
    }

    void draw(Graphics graphics, String text, int x, int y, int color,
              int scale, int spacing) {
        if (text == null) {
            return;
        }
        graphics.setColor(color);
        int cursor = x;
        int i;
        for (i = 0; i < text.length(); i++) {
            int glyph = glyphIndex(text.charAt(i));
            drawGlyph(graphics, glyph, cursor, y, scale);
            cursor += WIDTHS[glyph] * scale + spacing;
        }
    }

    private static void drawGlyph(Graphics graphics, int glyph, int left, int top,
                                  int scale) {
        int width = WIDTHS[glyph];
        int y;
        int x;
        for (y = 0; y < HEIGHT; y++) {
            int row = ROWS[glyph][y] & 0xFFFF;
            if (row == 0) {
                continue;
            }
            for (x = 0; x < width; x++) {
                if ((row & (1 << (width - 1 - x))) != 0) {
                    graphics.fillRect(left + x * scale, top + y * scale,
                        scale, scale);
                }
            }
        }
    }

    private static int glyphIndex(char character) {
        if (character >= 'a' && character <= 'z') {
            character = (char) (character - ('a' - 'A'));
        }
        int index = CHARSET.indexOf(character);
        if (index >= 0) {
            return index;
        }
        return CHARSET.indexOf('?');
    }
